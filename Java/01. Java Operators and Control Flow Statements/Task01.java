public class Task01{

    public static void main(String[]args){

        int a = 20;
        int b = 6;

        // Addition //
        System.out.println(a + b);

        // Subtraction //
        System.out.println(a - b);

        // Multiplication //
        System.out.println(a * b);

        // Division //
        System.out.println(b / a);

        // Extra //

        // Modulus // 
        System.out.println(a % b);

        // All //
        System.out.println(a + b - b * a / b % a);
    }
}